export function getUpcomingEvents(referenceDate = new Date()) {
  const today = new Date(referenceDate.getFullYear(), referenceDate.getMonth(), referenceDate.getDate()).getTime();
  return events
    .filter(event => new Date(`${event.date}T23:59:59`).getTime() >= today)
    .sort((a, b) => a.date.localeCompare(b.date));
}
